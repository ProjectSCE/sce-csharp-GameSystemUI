namespace GameSystemUI.ConversationSystemUI.Data;

/// <summary>
/// 气泡方向枚举
/// </summary>
public enum BubbleDirection
{
    /// <summary>
    /// 上方（气泡指向上方，显示在单位下方）
    /// </summary>
    Up,
    
    /// <summary>
    /// 下方（气泡指向下方，显示在单位上方）
    /// </summary>
    Down,
    
    /// <summary>
    /// 左侧（气泡指向左侧，显示在单位右侧）
    /// </summary>
    Left,
    
    /// <summary>
    /// 右侧（气泡指向右侧，显示在单位左侧）
    /// </summary>
    Right
}

